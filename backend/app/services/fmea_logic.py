"""
AIAG-VDA 2019 FMEA Action Priority (AP) Logic
and S/O/D Rating Standards for DFMEA and PFMEA.
"""


def get_action_priority(severity: int, occurrence: int, detection: int) -> str:
    """
    Determine Action Priority (H/M/L) based on S-O-D combination.
    Strict AIAG-VDA 2019 logic.
    """
    s, o, d = severity, occurrence, detection

    # HIGH priority combinations
    if s >= 9:
        if o >= 4:
            return "H"
        if o >= 2 and d >= 4:
            return "H"
        if o >= 2 and d >= 2:
            return "H"
    if s >= 7:
        if o >= 6:
            return "H"
        if o >= 4 and d >= 4:
            return "H"
        if o >= 5 and d >= 3:
            return "H"
    if s >= 5:
        if o >= 8:
            return "H"
        if o >= 7 and d >= 4:
            return "H"
    if s >= 4:
        if o >= 9 and d >= 5:
            return "H"

    # LOW priority combinations
    if s <= 3 and o <= 3 and d <= 3:
        return "L"
    if s <= 2:
        return "L"
    if s <= 4 and o <= 3:
        return "L"
    if s <= 4 and o <= 4 and d <= 3:
        return "L"
    if s <= 5 and o <= 2:
        return "L"
    if s <= 6 and o <= 2 and d <= 3:
        return "L"
    if s <= 5 and o <= 3 and d <= 2:
        return "L"

    # Everything else is MEDIUM
    return "M"


